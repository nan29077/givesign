import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const base = 'http://localhost:3060';
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await ctx.newPage();
fs.mkdirSync('output/qa', { recursive: true });
try {
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.match(await page.locator('body').innerText(), /기브싸인/);
  assert.doesNotMatch(await page.locator('body').innerText(), /메시지페이|MessagePay|포인트 충전/);
  await page.screenshot({ path: 'output/qa/home-desktop.png', fullPage: true });
  await page.goto(base + '/login');
  await page.getByRole('button', { name: /사회복지기관 테스트 로그인/ }).click();
  await page.waitForURL('**/studio');
  await page.goto(base + '/studio/donation-page');
  await page.locator('input[name=title]').fill('기브싸인 저장 검증 후원페이지');
  await page.locator('input[name=published]').check();
  await page.getByRole('button', { name: '후원페이지 저장', exact: true }).click();
  await page.waitForURL('**/studio/donation-page?saved=1');
  await page.reload();
  assert.equal(await page.locator('input[name=title]').inputValue(), '기브싸인 저장 검증 후원페이지');
  await page.goto(base + '/studio/campaigns/new');
  await page.locator('input[name=title]').fill('이웃의 따뜻한 한 끼 (검수 캠페인)');
  await page.locator('input[name=summary]').fill('사회복지기관 캠페인 생성과 공개를 확인하는 테스트입니다.');
  await page.locator('input[name=goal]').fill('1000000');
  await page.locator('input[name=start]').fill('2026-10-01');
  await page.locator('input[name=end]').fill('2026-12-31');
  await page.locator('textarea[name=usage]').fill('도시락 재료와 전달 활동에 사용합니다.');
  await page.locator('input[name=published]').check();
  await page.getByRole('button', { name: '캠페인 저장', exact: true }).click();
  await page.waitForURL('**/studio/campaigns?saved=1');
  const edit = page.getByRole('link', { name: '수정', exact: true }).first();
  const editPath = await edit.getAttribute('href');
  await page.goto(base + '/donate/GIV-8K2M');
  assert.match(await page.locator('body').innerText(), /기브싸인 저장 검증 후원페이지/);
  await page.getByRole('link', { name: /이웃의 따뜻한 한 끼/ }).first().click();
  await page.waitForURL('**/campaigns/**');
  assert.match(await page.locator('body').innerText(), /도시락 재료와 전달 활동/);
  assert.match(await page.locator('a[href^="sms:"]').getAttribute('href'), /05051001001/);
  await page.screenshot({ path: 'output/qa/campaign-desktop.png', fullPage: true });
  // Anonymous visitors may read published pages, but may not edit institution settings.
  const anon = await browser.newContext();
  const ap = await anon.newPage();
  await ap.goto(base + '/studio/donation-page');
  assert.match(ap.url(), /login/);
  await ap.goto(base + '/donate/GIV-8K2M');
  assert.match(await ap.locator('body').innerText(), /기브싸인 저장 검증 후원페이지/);
  await anon.close();
  // Edit, unpublish and check anonymous visibility.
  await page.goto(base + editPath);
  await page.locator('input[name=title]').fill('이웃의 따뜻한 한 끼 (수정 검증)');
  await page.locator('input[name=published]').uncheck();
  await page.getByRole('button', { name: '캠페인 저장', exact: true }).click();
  await page.waitForURL('**/studio/campaigns?saved=1');
  await page.goto(base + '/studio/donation-page');
  await page.locator('input[name=title]').fill('작은 나눔이 이웃의 든든한 한 끼가 됩니다');
  await page.getByRole('button', { name: '후원페이지 저장', exact: true }).click();
  await page.waitForURL('**/studio/donation-page?saved=1');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  await page.screenshot({ path: 'output/qa/home-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile overflow');
  console.log('PASS: institution test login, persistent page settings, campaign create/edit, public MO link, anonymous access control, mobile layout');
} finally { await browser.close(); }
